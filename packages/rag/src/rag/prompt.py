"""
prompt.py — LLM 에게 전달할 프롬프트(메시지 목록) 조립 모듈

【프롬프트 엔지니어링이란?】
LLM이 원하는 형태의 답변을 내놓도록 입력 텍스트(프롬프트)를 정교하게 설계하는 기술입니다.
시스템 프롬프트에 역할, 답변 형식, 인용 규칙 등을 명시하면 LLM이 그에 맞춰 답변합니다.

【OpenAI 호환 메시지 형식】
이 프로젝트는 Qwen 모델을 사용하지만,
대부분의 최신 LLM 은 아래 형식을 공통으로 지원합니다:
  [
    {"role": "system", "content": "역할 및 규칙 설명"},
    {"role": "user",   "content": "사용자 질문"},
    {"role": "assistant", "content": "모델 답변"},  ← 학습 시에만 포함
  ]

【이 파일의 구조】
  ┌─────────────────────────────────┐
  │ SYSTEM_PROMPT                   │  역할·형식·인용 규칙 고정 텍스트
  └─────────────────────────────────┘
            ↓ build_messages() 로 조립
  ┌─────────────────────────────────┐
  │ [{"role": "system", ...},       │
  │  {"role": "user",               │
  │   "content":                    │
  │     "근거:\\n[1] 법조항 본문\\n     │
  │      [2] 판례 본문\\n\\n          │
  │      질문: ..."}]                │
  └─────────────────────────────────┘
"""

from .types import Retrieved  # 검색된 문서 데이터 타입

# ══════════════════════════════════════════════════════════════
# 시스템 프롬프트 (System Prompt)
# LLM 에게 역할, 답변 형식, 인용 규칙을 지시하는 고정 텍스트입니다.
# 모든 /chat 요청에 동일하게 포함됩니다.
# ══════════════════════════════════════════════════════════════
SYSTEM_PROMPT = (
    # 역할 설정: 주택임대차 보증금 문제 전문 상담 도우미
    "당신은 대한민국 주택임대차(특히 보증금 반환) 문제를 돕는 상담 도우미입니다. "
    # 근거 제한: RAG 로 검색된 문서만 사용. 외부 지식(환각) 사용 금지.
    "아래 '근거' 자료만 사용해 답하세요. 답변은 ① 상황 요약 ② 적용 법리 ③ 다음 절차 "
    # 답변 형식: 상담형 3단계 구조
    "순의 상담형으로 간결하게 작성합니다.\n"
    # 인용 규칙: 모든 사실 진술에 [n] 번호 필수
    "[인용 규칙 — 반드시 지킬 것] 사실·법리를 진술하는 모든 문장은 반드시 해당 근거 번호를 "
    "[1], [2]처럼 문장 끝 마침표 앞에 답니다. 근거 번호 없는 문장은 쓰지 마세요.\n"
    # 인용 예시: LLM 이 형식을 이해하도록 구체적인 예를 제공
    '예시: "임차인은 보증금을 우선변제 받을 수 있습니다[1]."\n'
    # 환각 방지 강화: 근거 없는 주장 금지
    "② 적용 법리의 모든 문단은 최소 하나의 근거 번호를 인용해야 합니다. 뒷받침할 근거가 없는 "
    "내용은 아예 진술하지 마세요. 근거가 부족하면 그 사실을 밝히세요.\n"
    # 면책 문구: 항상 마지막에 삽입 (pipeline.py 에서도 추가로 검사)
    "마지막 줄에는 반드시 다음 문장을 그대로 적으세요:\n"
    "※ 본 답변은 일반적 정보 제공이며 법률 자문이 아닙니다."
)


def build_messages(query: str, hits: list[Retrieved]) -> list[dict]:
    """검색된 문서와 사용자 질문을 LLM 메시지 형식으로 조립합니다.

    최종적으로 아래 형태의 메시지 목록을 반환합니다:
        [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": "근거:\\n[1] (법조항 A) ...본문...\\n\\n[2] (판례 B) ...본문...\\n\\n질문: ..."},
        ]

    각 근거 문서에는 번호 [1], [2], ... 를 붙여서 LLM 이 인용할 수 있게 합니다.
    시스템 프롬프트의 규칙에 따라 LLM 은 사실 진술 시 이 번호를 반드시 인용합니다.

    Args:
        query : 사용자가 입력한 질문 텍스트
        hits  : retriever.retrieve() 가 반환한 검색 결과 목록

    Returns:
        OpenAI 호환 메시지 딕셔너리 리스트 (system + user 2개 원소)
    """
    blocks = []

    # enumerate(hits, 1) : 인덱스를 1부터 시작합니다 (0이 아닌 1-indexed)
    # i=1 → "[1]", i=2 → "[2]" 형식으로 번호를 붙입니다.
    for i, h in enumerate(hits, 1):
        # 각 근거 블록 형식: "[번호] (제목) 본문 텍스트"
        # 예: "[1] (주택임대차보호법 제3조의3) 임차인은..."
        blocks.append(f"[{i}] ({h.title}) {h.text}")

    # 블록이 있으면 빈 줄 2개로 구분해서 연결, 없으면 "(관련 근거 없음)" 표시
    # (근거 없음 분기는 pipeline.py 의 is_grounded() 에서 미리 걸러지지만, 안전장치로 둡니다)
    grounds = "\n\n".join(blocks) if blocks else "(관련 근거 없음)"

    # 사용자 메시지: 근거 + 질문을 하나의 문자열로 구성
    user = f"근거:\n{grounds}\n\n질문: {query}"

    # OpenAI 호환 메시지 형식으로 반환
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]
